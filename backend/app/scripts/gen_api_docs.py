"""Generate docs/API.md from the running application's routes and OpenAPI schema.

    python -m app.scripts.gen_api_docs            # writes ../docs/API.md

The endpoint reference is generated, so it can't drift from the code. "Who can call it" is read
from each route's real dependencies (get_current_user / require_roles), not written by hand.
"""
import json
import os
from pathlib import Path

os.environ.setdefault("JWT_SECRET_KEY", "docs-generation-placeholder-not-a-real-secret-000")

from fastapi.routing import APIRoute  # noqa: E402

from app.api import deps  # noqa: E402
from app.core.config import BASE_DIR, settings  # noqa: E402
from app.main import app  # noqa: E402

OUT = BASE_DIR.parent / "docs" / "API.md"
TAG_ORDER = ["health", "auth", "users", "documents", "rag", "chat", "dashboard", "admin"]
TAG_TITLES = {"health": "Health", "auth": "Authentication", "users": "Current user", "documents": "Documents",
              "rag": "RAG query (stateless)", "chat": "Chat", "dashboard": "Dashboards", "admin": "Administration"}
ROLE_NAMES = {"admin": "Admin", "hr": "HR", "employee": "Employee"}

GUIDE = f"""# CorpMind API reference

Base URL: `/api/v1`. Interactive docs (try requests in the browser): **`/docs`** on the backend.
Machine-readable schema: `/api/v1/openapi.json`.

> This file is generated by `python -m app.scripts.gen_api_docs` from the application code.
> The guide sections at the top are hand-written; the endpoint reference below them is generated.

## Authentication

1. **Sign in**: `POST /auth/login` with `{{"email", "password"}}` returns
   `{{"access_token", "refresh_token", "token_type": "bearer", "expires_in"}}`. The response also sets the
   refresh token as an **httpOnly cookie** `corpmind_refresh` (path `/api/v1/auth`, `SameSite=Strict`), which is
   what the web app uses.
2. **Call the API** with `Authorization: Bearer <access_token>`. Access tokens last
   {settings.ACCESS_TOKEN_EXPIRE_MINUTES} minutes.
3. **Refresh**: `POST /auth/refresh`, with the refresh token in the cookie (browsers) or in the body
   `{{"refresh_token": "..."}}` (scripts). Each refresh **rotates** the token: the old one stops working. Re-using
   a rotated refresh token is treated as theft and revokes all of that user's sessions.
4. **Sign out**: `POST /auth/logout` revokes the refresh token and clears the cookie.

Roles are re-read from the database on every request, so a role change or deactivation applies immediately.

```bash
TOKEN=$(curl -s -X POST localhost:8000/api/v1/auth/login -H 'Content-Type: application/json' \\
  -d '{{"email":"you@company.com","password":"..."}}' | python -c "import sys,json;print(json.load(sys.stdin)['access_token'])")
curl -s localhost:8000/api/v1/users/me -H "Authorization: Bearer $TOKEN"
```

## Access control

| Role | Can do |
|---|---|
| Employee | Ask questions and read documents in the categories the Employee role can read |
| HR | Everything Employees can, in HR's categories; upload, version and delete documents in those categories |
| Admin | Everything, in every category; manage users, category access, analytics, feedback and the audit log |

Which categories each role can read is set in `role_category_permissions` (Admin → Access by category).
Every endpoint that returns document content filters by it **on the server**, and retrieval applies it inside
both the vector search and the keyword search. A document outside your categories returns **404, not 403**, so
its existence isn't revealed. The same applies to other users' conversations and messages.

## Errors

All errors are JSON with a `detail` field.

| Status | Meaning |
|---|---|
| 400 | The request can't be done as asked (e.g. reprocessing a version that didn't fail) |
| 401 | Missing, expired or invalid token. Refresh and retry once, then sign in again |
| 403 | Signed in, but your role can't do this |
| 404 | Not found, **or not visible to you** |
| 409 | Conflict: duplicate file, version still processing, category not empty |
| 422 | Validation error: `{{"detail": "Validation error", "errors": [{{"field", "message"}}]}}` |
| 429 | Rate limit exceeded |
| 503 | The LLM or the embedding model is unavailable. Nothing was saved; retry |
| 500 | Unexpected error. Details go only to the server log, keyed by the `X-Request-ID` response header |

## Rate limits

Per signed-in user (otherwise per client IP): sign-in, registration and refresh {settings.RATE_LIMIT_AUTH};
questions (`/rag/query`, `/chat/ask`) {settings.RATE_LIMIT_CHAT}; everything else {settings.RATE_LIMIT_DEFAULT}.
All are configurable in `.env`.

## Asking a question: the response

`POST /chat/ask` (stores the conversation) and `POST /rag/query` (stateless) run the same pipeline.
An answer looks like this:

```json
{{
  "answer": "Up to 10 unused annual leave days may be carried forward; they expire on 31 March [1].",
  "citations": [{{"index": 1, "chunk_id": "…", "document_id": "…", "title": "Leave Policy", "page": 2,
                 "section": null, "snippet": "Up to 10 unused annual leave days…", "relevance": 0.91}}],
  "grounded": true,
  "mode": "qa",
  "standalone_question": "How many unused leave days can I carry forward, and when do they expire?",
  "rewritten": false,
  "confidence": 0.84,
  "confidence_label": "high",
  "retrieval": {{"chunks_used": 3, "candidates_considered": 18, "reranked": true, "documents": ["Leave Policy"]}},
  "latency_ms": {{"retrieval": 140, "generation": 1900, "total": 2050}}
}}
```

- `[n]` markers in `answer` refer to `citations[].index`. Every marker is guaranteed to point to a real citation.
- `grounded: false` means the answer is exactly *"{"I couldn't find sufficient information in the available company documents to answer this question."}"*
- `mode` is `qa`, `summarize`, `compare` or `small_talk`.
- To read a cited passage, call `GET /documents/chunks/{{chunk_id}}`; access is re-checked.
"""


def _access(route: APIRoute) -> str:
    """Work out who may call a route from its dependency tree."""
    roles, authed = None, False

    def walk(dep):
        nonlocal roles, authed
        call = dep.call
        if call is deps.get_current_user:
            authed = True
        if getattr(call, "__name__", "") == "checker" and call.__closure__:
            for cell in call.__closure__:
                val = cell.cell_contents
                if isinstance(val, set) and val and all(hasattr(r, "value") for r in val):
                    roles = val
        for sub in dep.dependencies:
            walk(sub)

    walk(route.dependant)
    if roles:
        return ", ".join(ROLE_NAMES[r.value] for r in sorted(roles, key=lambda r: list(ROLE_NAMES).index(r.value)))
    return "Any signed-in user" if authed else "Public"


def _schema_name(ref: dict | None) -> str:
    if not ref:
        return ""
    if "$ref" in ref:
        return ref["$ref"].rsplit("/", 1)[-1]
    if ref.get("type") == "array" and "items" in ref:
        return f"list of {_schema_name(ref['items'])}"
    if "anyOf" in ref:
        return " or ".join(_schema_name(x) for x in ref["anyOf"] if x.get("type") != "null")
    return ref.get("type", "")


def _fields(schema_name: str, components: dict) -> list[str]:
    s = components.get(schema_name, {})
    req = set(s.get("required", []))
    out = []
    for name, prop in s.get("properties", {}).items():
        typ = _schema_name(prop) or "any"
        bits = []
        if "maxLength" in prop:
            bits.append(f"max {prop['maxLength']} chars")
        if "enum" in prop:
            bits.append(" / ".join(map(str, prop["enum"])))
        if prop.get("description"):
            bits.append(prop["description"])
        out.append(f"`{name}` ({typ}{', required' if name in req else ''}){': ' + '; '.join(bits) if bits else ''}")
    return out


def _first_paragraph(text: str | None) -> str:
    return " ".join((text or "").strip().split("\n\n")[0].split()) if text else ""


def _iter_routes(routes, prefix: str = ""):
    """Yield (full_path, APIRoute). Recent FastAPI keeps included routers nested rather than flattened."""
    for r in routes:
        if isinstance(r, APIRoute):
            yield prefix + r.path_format, r
        elif hasattr(r, "original_router") and hasattr(r, "include_context"):
            yield from _iter_routes(r.original_router.routes, prefix + r.include_context.prefix)


def build() -> str:
    spec = app.openapi()
    components = spec.get("components", {}).get("schemas", {})
    by_tag: dict[str, list] = {}
    for full_path, route in _iter_routes(app.routes):
        tag = (route.tags or ["other"])[0]
        for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
            op = spec["paths"][full_path][method.lower()]
            by_tag.setdefault(tag, []).append((full_path, route, method, op))

    lines = [GUIDE, "## Endpoint summary", ""]
    lines += ["| Method | Path | Who can call it |", "|---|---|---|"]
    for tag in TAG_ORDER + [t for t in by_tag if t not in TAG_ORDER]:
        for full_path, route, method, _ in by_tag.get(tag, []):
            lines.append(f"| {method} | `{full_path.removeprefix(settings.API_PREFIX)}` | {_access(route)} |")

    for tag in TAG_ORDER + [t for t in by_tag if t not in TAG_ORDER]:
        if tag not in by_tag:
            continue
        lines += ["", f"## {TAG_TITLES.get(tag, tag.title())}", ""]
        for full_path, route, method, op in by_tag[tag]:
            path = full_path.removeprefix(settings.API_PREFIX)
            lines += [f"### `{method} {path}`", "", f"**Who:** {_access(route)}"]
            desc = _first_paragraph(op.get("description")) or op.get("summary", "")
            if desc:
                lines += ["", desc]
            params = [p for p in op.get("parameters", []) if p["in"] in ("path", "query")]
            if params:
                lines += ["", "**Parameters:** " + "; ".join(
                    f"`{p['name']}` ({p['in']}{', required' if p.get('required') else ''}"
                    f"{', ' + _schema_name(p.get('schema')) if _schema_name(p.get('schema')) else ''})" for p in params)]
            body = op.get("requestBody", {}).get("content", {})
            for ctype, content in body.items():
                name = _schema_name(content.get("schema"))
                kind = "multipart form" if "multipart" in ctype else "JSON body"
                flds = _fields(name, components)
                if flds:
                    lines += ["", f"**{kind.capitalize()}:**", ""] + [f"- {f}" for f in flds]
            ok = next((c for c in ("200", "201", "202", "204", "207") if c in op.get("responses", {})), None)
            if ok:
                resp = op["responses"][ok].get("content", {}).get("application/json", {}).get("schema")
                name = _schema_name(resp)
                lines += ["", f"**Returns:** {ok}" + (f", {name}" if name and name != "object" else "")]
            lines.append("")
    lines += ["", "## Schemas", "", "Response and request models referenced above.", ""]
    for name in sorted(components):
        if name.startswith(("HTTPValidationError", "ValidationError", "Body_")):
            continue
        flds = _fields(name, components)
        if flds:
            lines += [f"### {name}", ""] + [f"- {f}" for f in flds] + [""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    (OUT.parent / "openapi.json").write_text(json.dumps(app.openapi(), indent=2), encoding="utf-8")
    print(f"Wrote {OUT} and {OUT.parent / 'openapi.json'}")


if __name__ == "__main__":
    main()
